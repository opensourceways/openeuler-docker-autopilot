#!/usr/bin/env python3
"""
Stage: 场景四单软件功能测试脚本生成（testgen_generate）

对一个缺 test.sh 的存量应用：AI Agent 按 KunpengTest 规范生成
{domain}/{app}/tests/test.sh → 静态校验（失败带报告重试，最多 2 轮）→
给该软件最新 Dockerfile 追加一个空行（触发目标仓绑定的构建+测试 CI）→
commit 并推送 fork → 创建跨仓 PR（一软件一 PR）。

输入: --item '<json>'（解析阶段的产物：app/domain/version/os_version/source_url）
环境: AI_API_KEY（兼容 DEEPSEEK_API_KEY）, GITCODE_TOKEN, GITCODE_FORK_REPO(可选),
      SOURCE_REPO_DIR(默认 PROJECT_ROOT/source-repo), TARGET_REPO, TARGET_BRANCH,
      GIT_COMMIT_NAME/GIT_COMMIT_EMAIL
输出: 退出码 0（已交付 PR）；静态校验 2 轮仍不通过 → 1
"""

import argparse
import glob
import json
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

PROJECT_ROOT = str(Path(__file__).resolve().parent.parent.parent)
sys.path.insert(0, PROJECT_ROOT)

from scripts.lib import ai_provider
from scripts.lib.agent_runtime import run_agent  # noqa: E402
from scripts.lib.ci_gitcode_api import (  # noqa: E402
    create_pull_request,
    find_any_pr_by_head_branch,
)
from scripts.lib.kunpeng_test_contract import check_test_script  # noqa: E402
from scripts.lib.stage_common import (  # noqa: E402
    agent_prompt_file,
    log_stage,
    normalize_repo,
)

DEFAULT_SOURCE_REPO_DIR = os.path.join(PROJECT_ROOT, "source-repo")
DEFAULT_TARGET_REPO = "openeuler/openeuler-docker-images"
DEFAULT_TARGET_BRANCH = "master"

# 首次生成 + 最多 2 轮修复。
MAX_REPAIR_ROUNDS = 2

REQUIRED_AGENT_KEYS = ("success", "files_created", "test_script_path", "summary")

_PR_BODY_TEMPLATE = """\
This PR adds a functional test script for **{app}** so the CI-bound image
build also exercises the container functionally.

- Test entry: `{test_path}` (application-level, version injected via `EXPECTED_VERSION`)
- Target Dockerfile touched with a trailing blank line only, to trigger the
  build+test CI bound to Dockerfile changes
- Upstream: {repo_url}
- Spec: [KunpengTest README](https://github.com/opensourceways/upstream-dashboard/blob/KunpengTest/README.md)
- Static checks passed: bash -n, no `set -e`, `test[A-Za-z0-9_]+` case names, \
PASS/FAIL convention, `EXPECTED_VERSION` guard, no docker operations, \
mktemp+trap cleanup

Generated by the scenario-four test-script workflow.
"""


def _env(name: str, default: str = "") -> str:
    return (os.environ.get(name) or default).strip()


def _redact(text: str) -> str:
    """Strip the push token out of anything destined for the logs."""
    return re.sub(r"oauth2:[^@]+@", "oauth2:***@", text)


def _git(repo_dir: Path, *args: str, check: bool = True) -> subprocess.CompletedProcess:
    completed = subprocess.run(
        ["git", "-C", str(repo_dir), *args],
        capture_output=True,
        text=True,
        check=False,
    )
    if check and completed.returncode != 0:
        # git 的失败原因只在 stderr 里；不显式打出来，Actions 日志里就只剩一个
        # 退出码，排查得靠猜。
        detail = _redact((completed.stderr or completed.stdout or "").strip())
        raise RuntimeError(
            f"git {_redact(' '.join(args))} failed "
            f"({completed.returncode}): {detail[:2000]}"
        )
    return completed


def branch_name(app: str) -> str:
    return f"auto/test-script/{app}"


def _sample_paths(repo_dir: Path, domain: str, app: str) -> list[str]:
    """Up to two existing test.sh entries in the same domain as style refs."""
    pattern = str(repo_dir / domain / "*" / "tests" / "test.sh")
    return [
        os.path.relpath(p, repo_dir).replace(os.sep, "/")
        for p in sorted(glob.glob(pattern))
        if app not in Path(p).parts
    ][:2]


def build_prompt(
    *,
    app: str,
    domain: str,
    dockerfile_rel: str,
    source_url: str,
    latest_version: str,
    sample_paths: list[str],
    findings: list[dict] | None = None,
) -> str:
    """Assemble the creator prompt: role file + contract (+ repair report)."""
    prompt = Path(agent_prompt_file("testgen-creator")).read_text(encoding="utf-8")
    contract = {
        "package_name": app,
        "domain": domain,
        "dockerfile_path": dockerfile_rel,
        "repo_url": source_url,
        "latest_version": latest_version,
        "sample_test_paths": sample_paths,
        "allowed_new_paths": [f"{domain}/{app}/tests/"],
    }
    prompt += (
        "\n\n## Immutable task contract\n\n"
        + json.dumps(contract, indent=2, ensure_ascii=False)
        + "\n\n## Additional constraints\n\n"
        "- 只允许在 allowed_new_paths 下的 tests/ 目录创建文件；不得修改、"
        "移动或删除任何现有文件。\n"
        "- 不得运行任何 git 写操作或平台 API。\n"
    )
    if findings:
        prompt += (
            "\n## Static contract report to resolve\n\n"
            "上一轮生成的 test.sh 未通过 KunpengTest 静态校验，逐条修复后"
            "重新生成完整脚本：\n"
            + json.dumps(findings, indent=2, ensure_ascii=False)
            + "\n"
        )
    prompt += (
        "\n## Final response contract\n\n"
        "最终响应必须恰好是一个 JSON 对象，包含以下键："
        "success(bool)、package_name(str)、test_script_path(str)、"
        "files_created(list[str])、command_evidence(list)、summary(str)、"
        "error(null 或 str)。\n"
    )
    return prompt


def append_blank_line(path: Path) -> bool:
    """Append one blank line to a text file, preserving its EOL style.

    Idempotent: a file that already ends with a blank line is left alone.
    Returns True when the file changed.
    """
    data = path.read_bytes()
    eol = b"\r\n" if b"\r\n" in data else b"\n"
    if data.endswith(eol + eol):
        return False
    if not data.endswith(eol):
        data += eol
    path.write_bytes(data + eol)
    return True


def _scope_findings(repo_dir: Path, allowed_prefix: str) -> list[dict]:
    """Findings for any working-tree change outside the tests directory."""
    status = _git(repo_dir, "status", "--porcelain").stdout.splitlines()
    findings: list[dict] = []
    for line in status:
        entry = line[3:].strip().strip('"')
        if not entry.startswith(allowed_prefix):
            findings.append(
                {
                    "code": "kunpeng.scope_violation",
                    "level": "delivery_stop",
                    "owner": "testgen_creator",
                    "source": "kunpeng_test_protocol",
                    "message": f"unexpected change outside {allowed_prefix}: {entry}",
                    "check": "kunpeng_contract",
                }
            )
    return findings


def _reset_workspace(repo_dir: Path, allowed_prefix: str) -> None:
    """Drop any leftover change from a previous round before re-running."""
    _git(repo_dir, "checkout", "--", ".", check=False)
    _git(repo_dir, "clean", "-fd", check=False)


def generate_test_script(
    *,
    repo_dir: Path,
    app: str,
    domain: str,
    dockerfile_rel: str,
    source_url: str,
    latest_version: str,
    api_key: str,
    executable: Path,
) -> list[dict]:
    """Run the creator with repair rounds. Returns the final findings."""
    test_rel = f"{domain}/{app}/tests/test.sh"
    allowed_prefix = f"{domain}/{app}/tests/"
    findings: list[dict] = []
    for round_no in range(MAX_REPAIR_ROUNDS + 1):
        _reset_workspace(repo_dir, allowed_prefix)
        prompt = build_prompt(
            app=app,
            domain=domain,
            dockerfile_rel=dockerfile_rel,
            source_url=source_url,
            latest_version=latest_version,
            sample_paths=_sample_paths(repo_dir, domain, app),
            findings=findings or None,
        )
        log_stage("testgen", f"{app}: agent round {round_no + 1}")
        run_agent(
            executable=Path(executable),
            role="testgen_creator",
            prompt=prompt,
            workspace=repo_dir,
            api_key=api_key,
            required_keys=REQUIRED_AGENT_KEYS,
        )
        findings = check_test_script(repo_dir / test_rel)
        findings += _scope_findings(repo_dir, allowed_prefix)
        if not findings:
            return []
        log_stage("testgen", f"{app}: findings={len(findings)}")
    return findings


def deliver(
    *,
    repo_dir: Path,
    app: str,
    domain: str,
    dockerfile_rel: str,
    source_url: str,
) -> str:
    """Commit, push to the fork and open the cross-repo PR."""
    branch = branch_name(app)
    test_rel = f"{domain}/{app}/tests/test.sh"

    test_path = repo_dir / test_rel
    test_path.chmod(test_path.stat().st_mode | 0o111)

    dockerfile = repo_dir / dockerfile_rel
    if append_blank_line(dockerfile):
        log_stage("testgen", f"{app}: Dockerfile blank line appended")
    else:
        log_stage("testgen", f"{app}: Dockerfile already ends blank, skip")

    _git(repo_dir, "add", test_rel, dockerfile_rel)
    _git(repo_dir, "add", f"{domain}/{app}/tests")
    commit_name = _env("GIT_COMMIT_NAME", "github-actions[bot]")
    commit_email = _env("GIT_COMMIT_EMAIL", "github-actions[bot]@users.noreply.github.com")
    _git(
        repo_dir,
        "-c", f"user.name={commit_name}",
        "-c", f"user.email={commit_email}",
        "commit", "-m", f"test: add functional test for {app}",
    )

    token = _env("GITCODE_TOKEN")
    if not token:
        raise SystemExit("GITCODE_TOKEN is required to deliver the test script PR")
    target_repo = _env("TARGET_REPO", DEFAULT_TARGET_REPO)
    base_branch = _env("TARGET_BRANCH", DEFAULT_TARGET_BRANCH)
    fork_repo = normalize_repo(_env("GITCODE_FORK_REPO"))
    push_repo = fork_repo or target_repo
    push_url = f"https://oauth2:{token}@gitcode.com/{push_repo}.git"
    _git(repo_dir, "push", push_url, f"+refs/heads/{branch}:refs/heads/{branch}")

    head = f"{push_repo.split('/')[0]}:{branch}" if push_repo != target_repo else branch
    existing = find_any_pr_by_head_branch(target_repo, branch, token, open_only=True)
    if existing:
        pr_url = str(existing.get("web_url") or existing.get("html_url") or "")
        log_stage("testgen", f"{app}: open PR already exists ({pr_url or 'unknown url'})")
    else:
        title = f"test: add functional test for {app}"
        body = _PR_BODY_TEMPLATE.format(
            app=app,
            test_path=test_rel,
            repo_url=source_url or "unknown upstream",
        )
        pr = create_pull_request(target_repo, head, base_branch, title, body, token)
        pr_url = str(pr.get("web_url") or pr.get("html_url") or "")
        log_stage("testgen", f"{app}: PR created {pr_url}")
    return pr_url


def run_generate(item: dict) -> int:
    app = str(item["app"])
    domain = str(item["domain"])
    version = str(item["version"])
    os_version = str(item["os_version"])
    source_url = str(item.get("source_url", ""))

    repo_dir = Path(_env("SOURCE_REPO_DIR", DEFAULT_SOURCE_REPO_DIR))
    if not repo_dir.is_dir():
        raise SystemExit(f"source repo not found: {repo_dir}")

    dockerfile_rel = f"{domain}/{app}/{version}/{os_version}/Dockerfile"
    if not (repo_dir / dockerfile_rel).is_file():
        log_stage("testgen", f"{app}: Dockerfile missing ({dockerfile_rel}), skip")
        return 0

    branch = branch_name(app)
    base_branch = _env("TARGET_BRANCH", DEFAULT_TARGET_BRANCH)
    checkout = _git(repo_dir, "checkout", "-B", branch, base_branch, check=False)
    if checkout.returncode != 0:
        # The clone may sit on a differently named default branch.
        _git(repo_dir, "checkout", "-B", branch, check=False)

    api_key = ai_provider.api_key()
    if not api_key:
        raise SystemExit(
            "AI_API_KEY (or DEEPSEEK_API_KEY) is required for script generation"
        )
    executable = os.environ.get("OPENCODE_BIN") or shutil.which("opencode")
    if not executable:
        raise SystemExit(
            "opencode CLI not found (set OPENCODE_BIN or install it on PATH)"
        )

    findings = generate_test_script(
        repo_dir=repo_dir,
        app=app,
        domain=domain,
        dockerfile_rel=dockerfile_rel,
        source_url=source_url,
        latest_version=version,
        api_key=api_key,
        executable=Path(executable),
    )
    if findings:
        reason = "\n".join(f"{f['code']}: {f['message']}" for f in findings)
        log_stage(
            "testgen",
            f"{app}: exhausted after {MAX_REPAIR_ROUNDS + 1} rounds\n{reason}",
        )
        return 1

    pr_url = deliver(
        repo_dir=repo_dir,
        app=app,
        domain=domain,
        dockerfile_rel=dockerfile_rel,
        source_url=source_url,
    )
    log_stage("testgen", f"{app}: delivered {pr_url or '(url unavailable)'}")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--item",
        required=True,
        help="resolved item JSON: "
        '{"app": "...", "domain": "...", "version": "...", '
        '"os_version": "...", "source_url": "..."}',
    )
    args = parser.parse_args()
    return run_generate(json.loads(args.item))


if __name__ == "__main__":
    sys.exit(main())
